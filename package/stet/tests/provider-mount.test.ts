/**
 * The CopyProvider mount's inverse: `unmountEdits` takes out exactly the mount
 * `init` (0.6.0, the `resolveAll` form over `{children}`) or `register` (0.7.0,
 * the `resolved` form over `<body>`'s content) wrote, proven by the round trip,
 * and answers null for a mount the host has changed.
 */
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

import { describe, expect, it } from 'vitest';

import { defaultConfig, type StetConfig } from '../cli/config.js';
import { importsCopyProvider, locateWrapTarget, providerEdits, unmountEdits } from '../cli/provider-mount.js';
import { applyFileEdits } from '../cli/rewrite.js';
import { loadTypescript, scriptKindFor } from '../cli/source-scan.js';

/** `create-next-app`'s `app/layout.tsx`. */
const CNA_LAYOUT = `import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      <body className={\`\${geistSans.variable} \${geistMono.variable}\`}>
        {children}
      </body>
    </html>
  );
}
`;

/** The same layout as 0.6.0's `init --yes` left it (the lab's adoption). */
const CNA_MOUNTED_060 = CNA_LAYOUT.replace(
  'import "./globals.css";\n',
  'import "./globals.css";\n' +
    "import { CopyProvider } from '@getstet/stet/react';\n" +
    "import { readBundle, resolveAll, type Descriptor } from '@getstet/stet';\n" +
    "import descriptorJson from '../content/descriptor.json';\n" +
    "import { DEFAULTS } from '../content/defaults';\n" +
    '\n' +
    'const { resolved } = resolveAll(descriptorJson as unknown as Descriptor, readBundle(DEFAULTS));\n' +
    '\n',
).replace('        {children}\n', '        <CopyProvider descriptor={descriptorJson as unknown as Descriptor} resolved={resolved}>{children}</CopyProvider>\n');

const PAGES_APP =
  "import type { AppProps } from 'next/app';\nimport '../styles/globals.css';\n\nexport default function App({ Component, pageProps }: AppProps) {\n  return <Component {...pageProps} />;\n}\n";

/** The Vite `react-ts` template's `src/main.tsx`. */
const VITE_MAIN =
  "import { StrictMode } from 'react'\nimport { createRoot } from 'react-dom/client'\nimport './index.css'\nimport App from './App.tsx'\n\n" +
  "createRoot(document.getElementById('root')!).render(\n  <StrictMode>\n    <App />\n  </StrictMode>,\n)\n";

const crlf = (text: string): string => text.replace(/\n/g, '\r\n');

interface Layout {
  cwd: string;
  path: string;
  config: StetConfig;
}

function layout(file: string, text: string, router: StetConfig['router'] = 'app'): Layout {
  const cwd = mkdtempSync(join(tmpdir(), 'stet-provider-mount-'));
  const path = join(cwd, file);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
  return { cwd, path, config: { ...defaultConfig(), router, rootLayout: file } };
}

/** The mount as `planMount` (the `resolved` form) or 0.6.0's `init` (the `resolveAll` form) writes it. */
async function mount(at: Layout, text: string, form: 'resolved' | 'resolveAll'): Promise<string> {
  const ts = await loadTypescript();
  const sf = ts.createSourceFile(at.path, text, ts.ScriptTarget.Latest, true, scriptKindFor(ts, at.path));
  expect(importsCopyProvider(ts, sf)).toBe(false);
  const wrap = locateWrapTarget(ts, sf, at.config.router as 'app' | 'pages' | 'vite', form);
  if (wrap === null) throw new Error('no wrap target');
  return applyFileEdits(text, providerEdits(ts, sf, text, at.path, at.cwd, at.config, wrap, form));
}

async function unmount(at: Layout, text: string): Promise<string | null> {
  const ts = await loadTypescript();
  const edits = unmountEdits(ts, at.path, text, at.cwd, at.config);
  return edits === null ? null : applyFileEdits(text, edits.edits);
}

const OPEN = '<CopyProvider descriptor={descriptorJson as unknown as Descriptor} resolved={RESOLVED}>';

describe('unmountEdits — the round trip', () => {
  for (const [eol, convert] of [
    ['LF', (text: string) => text],
    ['CRLF', crlf],
  ] as const) {
    it(`create-next-app's layout, the resolved form over <body>'s content (${eol})`, async () => {
      const original = convert(CNA_LAYOUT);
      const at = layout('app/layout.tsx', original);
      const mounted = await mount(at, original, 'resolved');
      expect(mounted).toContain(`<body className={\`\${geistSans.variable} \${geistMono.variable}\`}>${OPEN}`);
      expect(await unmount(at, mounted)).toBe(original);
    });

    it(`create-next-app's layout, the resolveAll form over {children} (${eol})`, async () => {
      const original = convert(CNA_LAYOUT);
      const at = layout('app/layout.tsx', original);
      const mounted = await mount(at, original, 'resolveAll');
      expect(mounted).toBe(convert(CNA_MOUNTED_060));
      expect(await unmount(at, mounted)).toBe(original);
    });

    it(`a Pages _app in both forms (${eol})`, async () => {
      const original = convert(PAGES_APP);
      const at = layout('pages/_app.tsx', original, 'pages');
      for (const form of ['resolved', 'resolveAll'] as const) expect(await unmount(at, await mount(at, original, form))).toBe(original);
    });
  }

  it("unmounts the lab's 0.6.0 mount to create-next-app's bytes", async () => {
    const at = layout('app/layout.tsx', CNA_MOUNTED_060);
    expect(await unmount(at, CNA_MOUNTED_060)).toBe(CNA_LAYOUT);
  });

  it("round-trips a mount with register's own leaf import inserted after the block, in the one-run and two-run shapes", async () => {
    const nav = CNA_LAYOUT.replace('import "./globals.css";\n', 'import "./globals.css";\nimport { Nav } from "./components/Nav";\n').replace(
      '        {children}\n',
      '        <Nav />\n        {children}\n',
    );
    const at = layout('app/layout.tsx', nav);
    const mounted = await mount(at, nav, 'resolved');
    const LEAF = "import { copy } from '@/lib/content';";
    const leafAfterNav = nav.replace('import { Nav } from "./components/Nav";', `import { Nav } from "./components/Nav";\n${LEAF}`);
    // One run: the mount and the leaf import both insert after `import { Nav }`, the block first.
    const oneRun = mounted.replace("import { RESOLVED } from '../content/resolved';\n\n", `import { RESOLVED } from '../content/resolved';\n\n${LEAF}\n`);
    expect(oneRun).not.toBe(mounted);
    expect(await unmount(at, oneRun)).toBe(leafAfterNav);
    // Two runs: the later run's leaf import lands right after the block's last line,
    // so the newline the mount added after the block now follows the leaf import and stays.
    const twoRuns = mounted.replace("import { RESOLVED } from '../content/resolved';", `import { RESOLVED } from '../content/resolved';\n${LEAF}`);
    expect(await unmount(at, twoRuns)).toBe(leafAfterNav.replace(`${LEAF}\n`, `${LEAF}\n\n`));
  });

  it('round-trips a resolveAll mount at offset 0, in a layout with no import', async () => {
    const bare = 'export default function RootLayout({ children }) {\n  return <html><body>{children}</body></html>;\n}\n';
    for (const file of ['app/layout.tsx', 'app/layout.jsx']) {
      const at = layout(file, bare);
      const mounted = await mount(at, bare, 'resolveAll');
      expect(mounted.startsWith("import { CopyProvider } from '@getstet/stet/react';")).toBe(true);
      expect(await unmount(at, mounted)).toBe(bare);
    }
  });

  it("round-trips a Vite main.tsx, the mount over render's argument", async () => {
    const at = layout('src/main.tsx', VITE_MAIN, 'vite');
    const mounted = await mount(at, VITE_MAIN, 'resolved');
    expect(mounted).toContain(`.render(\n  ${OPEN}<StrictMode>`);
    expect(await unmount(at, mounted)).toBe(VITE_MAIN);
  });
});

describe('unmountEdits — a mount the host has changed', () => {
  it('answers null for a reformatted mount: the opening tag wrapped over two lines', async () => {
    const at = layout('app/layout.tsx', CNA_LAYOUT);
    const mounted = await mount(at, CNA_LAYOUT, 'resolved');
    const reformatted = mounted.replace(OPEN, '<CopyProvider\n          descriptor={descriptorJson as unknown as Descriptor} resolved={RESOLVED}>');
    expect(await unmount(at, reformatted)).toBeNull();
  });

  it('answers null for a layout carrying two CopyProviders', async () => {
    const at = layout('app/layout.tsx', CNA_LAYOUT);
    const mounted = await mount(at, CNA_LAYOUT, 'resolveAll');
    const twice = mounted.replace('</body>', `  <CopyProvider descriptor={descriptorJson as unknown as Descriptor} resolved={resolved}><footer /></CopyProvider>\n      </body>`);
    expect(await unmount(at, twice)).toBeNull();
  });
});
