export function usageCache(): UsageCache {
  return { keys: '', files: new Map() };
}

/** The source files the scan reads. */
const SOURCE = /\.(?:[cm]?[jt]sx?|astro|vue|svelte|mdx|html)$/;
/** Whether a repo-relative path is a source file the scan reads, by its extension. */
export const isSourceFile = (rel: string): boolean => SOURCE.test(rel);

/** The first line a stet-generated module carries. */
const GENERATED = '// generated by stet';

/** A mark on a static-HTML document: `data-stet="<key>"` or `data-stet-<attr>="<key>"`. */
const MARK = /data-stet(?:-[a-z-]+)?\s*=\s*["']([a-z][a-z0-9_]*)["']/g;

/** The cause a file too deeply nested to walk raises. */
const UNREADABLE = 'too deeply nested to read';

/** The cause a file past `MAX_SOURCE_BYTES` raises: it is never opened, so a key it names stays possible. */
const TOO_LARGE = 'over 5 MB, so the scan skipped it';

/** A cause's source text is cut here. */
const CAUSE_TEXT = 40;

/** The name stet's React hook is exported under. */
const HOOK = 'useCopy';

/** The functions a host calls to make an accessor of its own, which reads copy as the hook's result does. */
const ACCESSORS = ['createServerCopy', 'createAccessor'];

/**
 * A root is an import's local name, or a call of one: `useCopy()` for the
 * result of calling the import `useCopy`, `R.useCopy()` for a namespace
 * member. Neither spelling can be a JavaScript identifier. A namespace member
 * that is not called is a root of its own, `R.useCopy`, and `parseCall` takes
 * it for no call.
 */
function parseCall(root: string): { local: string; member?: string } | null {
  if (!root.endsWith('()')) return null;
  const inner = root.slice(0, -2);
  const dot = inner.indexOf('.');
  return dot < 0 ? { local: inner } : { local: inner.slice(0, dot), member: inner.slice(dot + 1) };
}

/** Names a call mutates an array or a map with, adding values the literal never held. */
const MUTATORS = new Set(['push', 'unshift', 'splice', 'fill', 'copyWithin']);

/** One read of a stet binding with no literal key, as pass 2 settled what it could on its own file. */
interface Read {
  /** The import local name the binding traces to, or `USE_COPY`. */
  root: string;
  line: number;
  text: string;
  /** B1: followed to key names in this file. */
  placed?: true;
  /** B1's adapter form: placed where every call of `name` passes a key-name literal at `index`. */
  adapter?: { name: string; index: number };
  /** B2: the prefixes in sight of this read. */
  prefixes: string[];
  /** A call of a candidate: the hook call itself where the callee is one, reached through `member` of a namespace. */
  hook?: { member?: string };
  /** The candidate itself goes somewhere as a value, reached through `member` of a namespace: a hook handed on is a hook unseen. */
  value?: { member?: string };
  /** The read is an argument of a call of a function imported from `@getstet/stet`, or of `Object.keys`. */
  exemptArg?: true;
}

/** One binding scope: a TypeScript file, a dialect component's scripts and markup, or a client script of its own. */
interface Scope {
  /** `imported` is the name in the module, `default`, or `*` for the module object itself. */
  imports: Array<{ local: string; spec: string; imported: string }>;
  reads: Read[];
  /** Roots this scope exports as a binding of its own: `export const copy = copyMap`, `export { copy }`. */
  exported: string[];
  /** Exported functions that return a hook call's result — `export const useT = () => useCopy()` — by the root they return. */
  wrappers: Array<{ name: string; root: string }>;
  /** Local names the module exports, by their own name. */
  exportedNames: string[];
  /** Import locals (and namespace members, `R.useCopy`) this scope exports under a name of its own. */
  aliased: Array<{ root: string; name: string }>;
  /** `require(spec)` or `import(spec)` in a shape too loose to bind: the module object goes somewhere unseen. */
  loose: Array<{ spec: string; line: number; text: string }>;
}

export interface FileFacts {
  /** Declared keys named in code. */
  named: string[];
  serverCode: boolean;
  /** Pass 2 skips the file: a test, a story, a fixture. */
  exempt: boolean;
  /** The file imports or re-exports `@getstet/stet` or one of its subpaths. */
  importsStet: boolean;
  /** The file nests too deeply to walk: its names are read by tokens and it is one cause. */
  unreadable?: true;
  /** `export … from '<spec>'`. */
  reexports: string[];
  /** `export { from as as }`, with or without a module, and `default` for a default export. */
  renames: Array<{ from: string; as: string }>;
  scopes: Scope[];
  /** Per callee name: how many calls, and the argument positions every one of them fills with a key-name literal. */
  calls: Map<string, { count: number; keyAt: number[] }>;
  /** Names used as values anywhere but as a callee — what disqualifies an adapter. */
  values: Set<string>;
  /** Strings that name the snapshot or a generated data module by path, outside an import: the data is read by a route unseen. */
  pathReads: Array<{ line: number; text: string }>;
}

/** What a string names when it points at the snapshot or a generated data module: their file names, and the folder they sit in. */
interface PathNeedles {
  names: string[];
  folder: string | null;
}

function pathNeedles(config: StetConfig): PathNeedles {
  const { defaults, resolved } = config.codegen;
  const folder = basename(posix.dirname(config.snapshotPath));
  return {
    names: [...new Set([config.snapshotPath, defaults, resolved].map((rel) => basename(rel)))],
    folder: folder === '.' || folder === '' ? null : folder,
  };
}

/**
 * Each source file's reads in the host at `cwd`: the keys it names, the
 * prefixes it reads under and the causes it stands for, its stet bindings
 * resolved across every file. The one reader `keyUsage` and the route reads
 * share. Needs `typescript`; its refusal is `loadTypescript`'s `CliError`.
 */
export async function siteReads(cwd: string, config: StetConfig, descriptor: Descriptor, cache: UsageCache = usageCache()): Promise<SiteReads> {
  const ts = await loadTypescript();
  const declared = new Set(Object.keys(descriptor.keys));
  const needles = pathNeedles(config);
  const stamp = [...[...declared].sort(), '', ...needles.names, needles.folder ?? ''].join('\n');
  if (cache.keys !== stamp) {
    cache.keys = stamp;
    cache.files.clear();
  }

  // Step 1: the files, each read and parsed only where its stamp moved.
  const facts = new Map<string, FileFacts>();
  const listed = new Set<string>();
  const { files: sources, tooLarge } = sourceFiles(cwd, config);
  for (const { rel, stamp: fileStamp } of sources) {
    listed.add(rel);
    const held = cache.files.get(rel);
    let found: FileFacts | null | 'grew';
    if (held !== undefined && held.stamp === fileStamp) found = held.facts;
    else {
      found = factsOf(ts, cwd, rel, declared, needles);
      cache.files.set(rel, { stamp: fileStamp, facts: found });
    }
    if (found === 'grew') tooLarge.push(rel);
    else if (found !== null) facts.set(rel, found);
  }
  for (const rel of [...cache.files.keys()]) if (!listed.has(rel)) cache.files.delete(rel);

  // Step 3: the modules a stet binding is imported from, widened by re-exports
  // round by round until no file is added. Beside them, the modules the hook
  // is imported from, and the names it goes by: `useCopy`, every exported
  // function that returns its result, and every re-export of either under
  // another name.
  const targets = new Set<string>([
    config.readPath.file,
    ...filesForGlobs(cwd, config.copyModules),
    config.codegen.defaults,
    config.codegen.resolved,
    config.snapshotPath,
  ]);
  const mappings = aliasMappings(ts, cwd);
  const dataAccepts = acceptor(cwd, mappings, new Set([config.codegen.defaults, config.codegen.resolved, config.snapshotPath]));
  const hookNames = new Set<string>([HOOK, ...ACCESSORS]);
  const hookModules = new Set<string>();
  let accepts = acceptor(cwd, mappings, targets, config.readPath.import);
  let hookAccepts = accepts;
  const hookBound = (rel: string, scope: Scope, root: string): boolean => {
    const call = parseCall(root);
    const imported = call === null ? undefined : scope.imports.find((i) => i.local === call.local);
    if (call === null || imported === undefined) return false;
    return hookNames.has(call.member ?? imported.imported) && (isStetPackage(imported.spec) || hookAccepts(rel)(imported.spec));
  };
  // A root that is the hook itself, not a call of it: an import local named in
  // `hookNames`, or a member of a namespace import that is.
  const hookRef = (rel: string, scope: Scope, root: string): boolean => {
    if (parseCall(root) !== null) return false;
    const dot = root.indexOf('.');
    const imported = scope.imports.find((i) => i.local === (dot < 0 ? root : root.slice(0, dot)));
    if (imported === undefined) return false;
    const name = dot < 0 ? imported.imported : imported.imported === '*' ? root.slice(dot + 1) : undefined;
    return name !== undefined && hookNames.has(name) && (isStetPackage(imported.spec) || hookAccepts(rel)(imported.spec));
  };
  const bound = (rel: string, scope: Scope, root: string): boolean =>
    parseCall(root) !== null ? hookBound(rel, scope, root) : scope.imports.some((i) => i.local === root && accepts(rel)(i.spec));
  for (let round = 0; round <= facts.size; round++) {
    let added = false;
    for (const [rel, file] of facts) {
      if (!targets.has(rel)) {
        const reexports =
          file.reexports.some((spec) => accepts(rel)(spec)) || file.scopes.some((s) => s.exported.some((root) => bound(rel, s, root)));
        if (reexports) {
          targets.add(rel);
          added = true;
        }
      }
      const wraps = file.scopes.flatMap((s) => s.wrappers.filter((w) => hookBound(rel, s, w.root)));
      if (!hookModules.has(rel) && (wraps.length > 0 || file.reexports.some((spec) => isStetPackage(spec) || hookAccepts(rel)(spec)))) {
        hookModules.add(rel);
        added = true;
      }
      // `export const useText = useCopy`, `export { useText }` after `const useText = useCopy`:
      // the hook goes on under the exported name, and the file is a hook module.
      for (const s of file.scopes) {
        for (const alias of s.aliased) {
          if (!hookRef(rel, s, alias.root)) continue;
          if (!hookModules.has(rel)) {
            hookModules.add(rel);
            added = true;
          }
          if (!hookNames.has(alias.name)) {
            hookNames.add(alias.name);
            added = true;
          }
        }
      }
      for (const w of wraps) {
        if (!hookNames.has(w.name)) {
          hookNames.add(w.name);
          added = true;
        }
      }
      for (const r of file.renames) {
        if (hookNames.has(r.from) && !hookNames.has(r.as)) {
          hookNames.add(r.as);
          added = true;
        }
      }
    }
    if (!added) break;
    accepts = acceptor(cwd, mappings, targets, config.readPath.import);
    hookAccepts = acceptor(cwd, mappings, new Set([...targets, ...hookModules]), config.readPath.import);
  }

  // Pass 2: the reads of a binding with no literal key, settled across files.
  const adapterHolds = (name: string, index: number): boolean => {
    let count = 0;
    for (const file of facts.values()) {
      if (file.values.has(name)) return false;
      const calls = file.calls.get(name);
      if (calls === undefined) continue;
      if (!calls.keyAt.includes(index)) return false;
      count += calls.count;
    }
    return count > 0;
  };
  // A file that imports stet hands its generated data whole to stet's own
  // functions by design: only a read rooted at one of those modules, as an
  // argument of such a call, is exempt there.
  const dataRooted = (rel: string, scope: Scope, root: string): boolean =>
    scope.imports.some((i) => i.local === root && dataAccepts(rel)(i.spec));
  const out = new Map<string, FileReads>();
  for (const [rel, file] of facts) {
    const reads: FileReads = { named: file.named, serverCode: file.serverCode, prefixes: [], causes: [] };
    out.set(rel, reads);
    const { prefixes, causes } = reads;
    if (file.exempt) continue;
    if (file.unreadable === true) {
      causes.push({ text: UNREADABLE, file: rel, line: 1 });
      continue;
    }
    for (const read of file.pathReads) causes.push({ text: read.text, file: rel, line: read.line });
    for (const scope of file.scopes) {
      for (const read of scope.reads) {
        // The hook handed on as a value, or held in an object: its calls are unseen.
        if (read.value !== undefined && hookRef(rel, scope, read.value.member === undefined ? read.root : `${read.root}.${read.value.member}`)) {
          causes.push({ text: read.text, file: rel, line: read.line });
          continue;
        }
        if (!bound(rel, scope, read.root)) continue;
        if (read.hook !== undefined && hookBound(rel, scope, read.hook.member === undefined ? `${read.root}()` : `${read.root}.${read.hook.member}()`)) continue;
        if (file.importsStet && read.exemptArg === true && dataRooted(rel, scope, read.root)) continue;
        if (read.placed === true) continue;
        if (read.adapter !== undefined && adapterHolds(read.adapter.name, read.adapter.index)) continue;
        if (read.prefixes.length > 0) {
          for (const prefix of read.prefixes) prefixes.push({ prefix, file: rel, line: read.line });
          continue;
        }
        causes.push({ text: read.text, file: rel, line: read.line });
      }
      for (const l of scope.loose) {
        if (!accepts(rel)(l.spec) || (file.importsStet && dataAccepts(rel)(l.spec))) continue;
        causes.push({ text: l.text, file: rel, line: l.line });
      }
    }
  }
  for (const rel of tooLarge) out.set(rel, { named: [], serverCode: false, prefixes: [], causes: [{ text: TOO_LARGE, file: rel, line: 1 }] });
  return { files: out, read: facts.size };
}

/**
 * Every declared key's state in the host at `cwd`, with the prefixes learnt,
 * the causes standing and the keys only server code names, over `siteReads`.
 */
export async function keyUsage(
  cwd: string,
  config: StetConfig,
  descriptor: Descriptor,
  cache: UsageCache = usageCache(),
): Promise<KeyUsage> {
  const site = await siteReads(cwd, config, descriptor, cache);
  // Pass 1: every name in code.
  const namedIn = new Map<string, string[]>();
  const prefixes: UsagePrefix[] = [];
  const causes: UsageCause[] = [];
  for (const [rel, file] of site.files) {
    for (const key of file.named) namedIn.set(key, [...(namedIn.get(key) ?? []), rel]);
    prefixes.push(...file.prefixes);
    causes.push(...file.causes);
  }
  const order = (a: { file: string; line: number }, b: { file: string; line: number }): number =>
    a.file < b.file ? -1 : a.file > b.file ? 1 : a.line - b.line;
  causes.sort(order);
  // A name with two roots reads once per root: one cause per place.
  const distinct = causes.filter((c, i) => i === 0 || c.file !== causes[i - 1]?.file || c.line !== causes[i - 1]?.line || c.text !== causes[i - 1]?.text);
  causes.splice(0, causes.length, ...distinct);
  prefixes.sort((a, b) => (a.prefix < b.prefix ? -1 : a.prefix > b.prefix ? 1 : order(a, b)));
  const learnt = prefixes.filter(
    (p, i) => i === 0 || p.prefix !== prefixes[i - 1]?.prefix || p.file !== prefixes[i - 1]?.file || p.line !== prefixes[i - 1]?.line,
  );

  // The states.
  const excluded = excludedKeys(descriptor);
  const keys: KeyUsage['keys'] = {};
  const serverOnly: string[] = [];
  for (const key of Object.keys(descriptor.keys)) {
    if (excluded.has(key)) continue;
    const files = namedIn.get(key);
    if (files !== undefined) {
      keys[key] = { state: 'read' };
      if (files.every((rel) => site.files.get(rel)?.serverCode === true)) serverOnly.push(key);
      continue;
    }
    let under: UsagePrefix | undefined;
    for (const p of learnt) if (key.startsWith(p.prefix) && (under === undefined || p.prefix.length > under.prefix.length)) under = p;
    if (under !== undefined) keys[key] = { state: 'unknown', prefix: under };
    else keys[key] = { state: causes.length > 0 ? 'unknown' : 'not_found' };
  }
  return { keys, prefixes: learnt, causes, serverOnly: serverOnly.sort(), files: site.read, root: rootOf(cwd) };
}

/**
 * The keys one file names in code: identifiers, property names and string
 * literals' contents equal to a declared key, outside comments and JSX text,
 * and in an `.html` file each `data-stet` mark. Pass 1 for one file.
 */
export function namedKeys(ts: typeof import('typescript'), file: string, source: string, declared: ReadonlySet<string>): Set<string> {
  const code = codeOf(ts, file, source, dialectOf(file));
  return code === null ? new Set() : namesIn(file, source, code.code, code.nonCode, declared);
}

function namesIn(file: string, source: string, code: Span[], nonCode: Span[], declared: ReadonlySet<string>): Set<string> {
  const named = new Set<string>();
  const inCode = spanTest(code);
  const inNonCode = spanTest(nonCode);
  // A key is a whole token: the run of word characters it sits in is the key.
  for (const m of source.matchAll(/[\w$]+/g)) {
    if (!declared.has(m[0]) || named.has(m[0])) continue;
    if (inCode(m.index) && !inNonCode(m.index)) named.add(m[0]);
  }
  if (file.endsWith('.html')) {
    for (const m of source.matchAll(MARK)) if (declared.has(m[1] as string)) named.add(m[1] as string);
  }
  return named;
}

/** `within`, by binary search over the merged spans. */
function spanTest(spans: Span[]): (at: number) => boolean {
  const sorted = [...spans].sort((a, b) => a.start - b.start);
  const merged: Span[] = [];
  for (const s of sorted) {
    const last = merged[merged.length - 1];
    if (last !== undefined && s.start <= last.end) last.end = Math.max(last.end, s.end);
    else merged.push({ start: s.start, end: s.end });
  }
  return (at) => {
    let lo = 0;
    let hi = merged.length;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      if ((merged[mid] as Span).end <= at) lo = mid + 1;
      else hi = mid;
    }
    return within(merged.slice(lo, lo + 1), at);
  };
}

/** `(rel) => (spec) => boolean` over the targets, a directory index answering for its directory too. */
function acceptor(
  cwd: string,
  mappings: readonly AliasMapping[],
  targets: ReadonlySet<string>,
  spelt?: string,
): (rel: string) => (spec: string) => boolean {
  const all = [...targets];
  for (const rel of targets) if (/(?:^|\/)index\.[cm]?[jt]sx?$/.test(rel)) all.push(dirname(rel));
  return moduleTest(cwd, mappings, all, spelt);
}

/** The extensions a specifier may spell either way: `./x.js` for `x.ts`, `./y.mjs` for `y.mts`, `./z.jsx` for `z.tsx`. */
const MODULE_EXT = /\.(?:[cm]?[jt]sx?|json)$/;
const stripExt = (path: string): string => path.replace(MODULE_EXT, '');

/** The `baseUrl` and `paths` a specifier resolves through; `baseUrl` is relative to the checkout. */
interface AliasMapping {
  baseUrl: string;
  paths: Record<string, unknown>;
}

/** One config file of an `extends` chain: where it sits and what it sets. */
interface ConfigLayer {
  dir: string;
  baseUrl?: string;
  paths?: Record<string, unknown>;
}

/** How many configs deep an `extends` chain is followed. */
const EXTENDS_DEPTH = 8;

/**
 * The host's path aliases: `tsconfig.json`, else `jsconfig.json`, with the
 * `extends` chain followed. A `paths` entry resolves against the `baseUrl` in
 * force where tsc reads it, else the folder of the config that declares it;
 * where the declaring config's own `baseUrl` says otherwise, that reading is
 * kept too, so a specifier lands on either.
 */
function aliasMappings(ts: typeof import('typescript'), cwd: string): AliasMapping[] {
  for (const name of ['tsconfig.json', 'jsconfig.json']) {
    const layers = configLayers(ts, join(cwd, name), []);
    if (layers === null) continue;
    const baseOf = (layer: ConfigLayer): string | undefined => (layer.baseUrl === undefined ? undefined : resolvePath(layer.dir, layer.baseUrl));
    let effective: string | undefined;
    let declaring: ConfigLayer | undefined;
    for (const layer of layers) {
      effective = baseOf(layer) ?? effective;
      if (layer.paths !== undefined) declaring = layer;
    }
    const own = layers[layers.length - 1] as ConfigLayer;
    const paths = declaring?.paths ?? {};
    const mapping = (base: string): AliasMapping => ({ baseUrl: relative(cwd, base) || '.', paths });
    const first = effective ?? declaring?.dir ?? own.dir;
    const out = [mapping(first)];
    const second = declaring === undefined ? undefined : (baseOf(declaring) ?? declaring.dir);
    if (second !== undefined && second !== first) out.push(mapping(second));
    return out;
  }
  return [];
}

/** A config and the configs it extends, the base first; null where the file cannot be read. */
function configLayers(ts: typeof import('typescript'), file: string, chain: readonly string[]): ConfigLayer[] | null {
  if (chain.includes(file) || chain.length >= EXTENDS_DEPTH) return null;
  let parsed: { config?: unknown; error?: unknown };
  try {
    parsed = ts.parseConfigFileTextToJson(file, readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
  const config = parsed.config as { extends?: unknown; compilerOptions?: unknown } | undefined;
  if (parsed.error !== undefined || typeof config !== 'object' || config === null) return null;
  const dir = dirname(file);
  const layers: ConfigLayer[] = [];
  const extended = typeof config.extends === 'string' ? [config.extends] : Array.isArray(config.extends) ? config.extends : [];
  for (const spec of extended) {
    const target = typeof spec === 'string' ? extendedFile(dir, spec) : null;
    layers.push(...((target === null ? null : configLayers(ts, target, [...chain, file])) ?? []));
  }
  const layer: ConfigLayer = { dir };
  const options = config.compilerOptions;
  if (typeof options === 'object' && options !== null) {
    const { baseUrl, paths } = options as { baseUrl?: unknown; paths?: unknown };
    if (typeof baseUrl === 'string') layer.baseUrl = baseUrl;
    if (typeof paths === 'object' && paths !== null && !Array.isArray(paths)) layer.paths = paths as Record<string, unknown>;
  }
  layers.push(layer);
  return layers;
}

/** The config file an `extends` names from `dir`: a relative path, or a package's `tsconfig.json` found up the `node_modules` chain. */
function extendedFile(dir: string, spec: string): string | null {
  const isFile = (path: string): boolean => {
    try {
      return statSync(path).isFile();
    } catch {
      return false;
    }
  };
  if (spec.startsWith('.') || isAbsolute(spec)) {
    const base = resolvePath(dir, spec);
    return [base, `${base}.json`].find(isFile) ?? null;
  }
  for (let at = dir; ; at = dirname(at)) {
    const base = join(at, 'node_modules', spec);
    const found = [base, `${base}.json`, join(base, 'tsconfig.json')].find(isFile);
    if (found !== undefined) return found;
    if (dirname(at) === at) return null;
  }
}

/** Whether a `paths` entry claims a specifier: an exact key, or a `prefix*suffix` pattern around it. */
export function declaresAlias(spec: string, paths: Record<string, unknown>): boolean {
  return Object.keys(paths).some((pattern) => {
    const star = pattern.indexOf('*');
    if (star < 0) return pattern === spec;
    return spec.length >= pattern.length - 1 && spec.startsWith(pattern.slice(0, star)) && spec.endsWith(pattern.slice(star + 1));
  });
}

/**
 * `(rel) => (spec) => boolean`: whether `spec`, imported from `rel`, lands on
 * one of `targets` (repo-relative files), extension aside. It lands there by
 * the host's own resolution (relative to the importer, through its path
 * aliases), by being spelt exactly as `spelt`, the specifier `register` wrote
 * into host files, or, for an alias nothing declares (`~/lib/content` under a
 * bundler's own alias, `lib/content` under a resolver root), by its path past
 * the alias prefix, or whole when it has none, ending a target's.
 */
function moduleTest(
  cwd: string,
  mappings: readonly AliasMapping[],
  targets: readonly string[],
  spelt: string | undefined,
): (rel: string) => (spec: string) => boolean {
  const wanted = new Set(targets.map((rel) => stripExt(join(cwd, rel))));
  const tails = targets.map((rel) => stripExt(rel));
  const packages = packageNames(cwd);
  const held = new Map<string, boolean>();
  const lands = (rel: string, spec: string): boolean => {
    if (spec === spelt) return true;
    for (const mapping of mappings.length === 0 ? [null] : mappings) {
      if (resolveSpecifier(spec, rel, cwd, mapping).some((path) => wanted.has(stripExt(path)))) return true;
    }
    if (spec.startsWith('.') || mappings.some((m) => declaresAlias(spec, m.paths))) return false;
    const segments = spec.split('/');
    if (segments.length < 2) return false;
    // `~/lib/content`: an alias prefix, then the path. `lib/content`: a bare
    // alias, its whole path ending a target's, unless its first segment is a
    // package of the project (`lodash/get`).
    const first = segments[0] as string;
    const aliased = /^[^A-Za-z0-9]/.test(first);
    if (!aliased && packages(spec)) return false;
    const tail = stripExt(aliased ? segments.slice(1).join('/') : spec);
    return tails.some((path) => path === tail || path.endsWith(`/${tail}`));
  };
  return (rel) => (spec) => {
    const key = `${spec.startsWith('.') ? dirname(rel) : ''}\0${spec}`;
    let answer = held.get(key);
    if (answer === undefined) {
      answer = lands(rel, spec);
      held.set(key, answer);
    }
    return answer;
  };
}

/**
 * The files stet writes or owns, which hold no read of copy: the read path, the
 * descriptor, the snapshot and every file `codegen` names. Repo-relative.
 */
export function ownFiles(config: StetConfig): Set<string> {
  const { registry, defaults, dts, resolved } = config.codegen;
  return new Set([config.readPath.file, config.descriptorPath, config.snapshotPath, registry, defaults, dts, resolved].map((rel) => posix.normalize(rel)));
}

/** Whether a module's text opens with the header stet puts on what it generates. */
export const isGenerated = (text: string): boolean => text.startsWith(GENERATED);

/**
 * Step 1: the checkout's tracked files and its untracked files git does not
 * ignore, filtered to source, with the skips that never hold a read: the files
 * stet owns (`ownFiles`), `.stet/`, a path that cannot be read, and a symlink
 * whose target lies outside the checkout. Where git cannot answer, the walk.
 * Each kept file carries its stamp. A file over `MAX_SOURCE_BYTES` is not kept
 * and is not opened: it is listed in `tooLarge`, since a key it names would
 * otherwise be called not found.
 */
function sourceFiles(cwd: string, config: StetConfig): { files: Array<{ rel: string; stamp: string }>; tooLarge: string[] } {
  const listed = gitFiles(cwd, ['--cached', '--others', '--exclude-standard']);
  const paths = listed === null ? filesForGlobs(cwd, ['**/*']) : [...new Set(listed)].sort();
  const own = ownFiles(config);
  const out: Array<{ rel: string; stamp: string }> = [];
  const tooLarge: string[] = [];
  for (const rel of paths) {
    if (!SOURCE.test(rel) || own.has(rel) || rel.startsWith('.stet/')) continue;
    const abs = join(cwd, rel);
    let stat: Stats;
    try {
      stat = lstatSync(abs);
      if (stat.isSymbolicLink()) {
        if (insideCheckout(cwd, abs) === null) continue;
        stat = statSync(abs);
      }
    } catch {
      continue; // listed by `--cached`, gone from the working tree
    }
    if (!stat.isFile()) continue;
    if (stat.size > MAX_SOURCE_BYTES) {
      tooLarge.push(rel);
      continue;
    }
    out.push({ rel, stamp: `${stat.size}:${stat.mtimeMs}` });
  }
  return { files: out, tooLarge };
}

/** `cwd` relative to the repository's top, `/`-ended; the folder's own name where it is the top or git cannot say. */
function rootOf(cwd: string): string {
  const prefix = gitData(cwd, ['rev-parse', '--show-prefix']);
  const rel = prefix.code === 0 ? prefix.stdout.trim() : '';
  return rel === '' ? `${basename(cwd)}/` : rel.endsWith('/') ? rel : `${rel}/`;
}

/** Keys that carry no state: `brand__*`, derived keys, page SEO fields, template slots. */
function excludedKeys(descriptor: Descriptor): Set<string> {
  const out = new Set<string>();
  for (const [key, def] of Object.entries(descriptor.keys)) {
    if (key.startsWith('brand__') || def.derivesFrom !== undefined) out.add(key);
  }
  for (const page of Object.values(descriptor.pages ?? {})) {
    for (const key of Object.values(page.seo ?? {})) if (typeof key === 'string') out.add(key);
  }
  for (const [name, template] of Object.entries(descriptor.templates ?? {})) {
    for (const slot of template.slots ?? []) out.add(`${name}__${slot}`);
  }
  return out;
}

/** The first bytes of a file, for the generated-header test. */
function headOf(abs: string): string {
  const fd = openSync(abs, 'r');
  try {
    const buffer = Buffer.alloc(64);
    return buffer.toString('utf8', 0, readSync(fd, buffer, 0, 64, 0));
  } finally {
    closeSync(fd);
  }
}

/** Server code: a Next route handler or middleware, an API route, an Astro endpoint, a `'use server'` module. */
function serverPath(rel: string): boolean {
  const segments = rel.split('/');
  const base = segments[segments.length - 1] ?? '';
  if (/^route\.[cm]?[jt]sx?$/.test(base) && segments.slice(0, -1).includes('app')) return true;
  if (/(?:^|\/)pages\/api\//.test(rel)) return true;
  if (/^middleware\.[cm]?[jt]sx?$/.test(base)) return true;
  return /(?:^|\/)src\/pages\/.+\.[jt]s$/.test(rel);
}

/** Pass 2 skips tests, stories and test fixtures; pass 1 still counts their names. */
function testPath(rel: string): boolean {
  return /(?:^|\/)(?:__tests__\/|__fixtures__\/|tests?\/fixtures\/)/.test(rel) || /\.(?:test|spec|stories)\.[^/]+$/.test(rel);
}

const isStetPackage = (spec: string): boolean => spec === '@getstet/stet' || spec.startsWith('@getstet/stet/');

/**
 * One file's facts: its named keys, whether it is server code or exempt, its
 * re-exports, and per scope its imports and its binding reads, B1 and B2
 * settled as far as the file alone can. Null for a generated module or a file
 * that cannot be read; `'grew'` for a file whose bytes passed the ceiling
 * after the stat that let it through.
 */
function factsOf(ts: typeof import('typescript'), cwd: string, rel: string, declared: ReadonlySet<string>, needles: PathNeedles): FileFacts | null | 'grew' {
  const abs = join(cwd, rel);
  let source: string;
  try {
    if (isGenerated(headOf(abs))) return null;
    const bytes = readFileSync(abs);
    // The file grew since the stat that passed it: skipped like one the stat caught.
    if (bytes.length > MAX_SOURCE_BYTES) return 'grew';
    source = bytes.toString('utf8');
  } catch {
    return null;
  }
  try {
    return readFacts(ts, rel, source, declared, needles);
  } catch (error) {
    if (!(error instanceof RangeError)) throw error;
    // A file nested past the compiler's recursion: its names by tokens, and one cause.
    const named = new Set<string>();
    for (const m of source.matchAll(/[\w$]+/g)) if (declared.has(m[0])) named.add(m[0]);
    return {
      named: [...named],
      serverCode: serverPath(rel),
      exempt: testPath(rel),
      importsStet: false,
      unreadable: true,
      reexports: [],
      renames: [],
      scopes: [],
      calls: new Map(),
      values: new Set(),
      pathReads: [],
    };
  }
}

function readFacts(ts: typeof import('typescript'), rel: string, source: string, declared: ReadonlySet<string>, needles: PathNeedles): FileFacts | null {
  const dialect = dialectOf(rel);
  const trees = new Map<number, TS.SourceFile>();
  const code = codeOf(ts, rel, source, dialect, (name, text, base) => {
    const sf = ts.createSourceFile(name, text, ts.ScriptTarget.Latest, true, scriptKindFor(ts, name));
    trees.set(base, sf);
    return sf;
  });
  if (code === null) return null;

  const facts: FileFacts = {
    named: [...namesIn(rel, source, code.code, code.nonCode, declared)],
    serverCode: serverPath(rel),
    exempt: testPath(rel),
    importsStet: false,
    reexports: [],
    renames: [],
    scopes: [],
    calls: new Map(),
    values: new Set(),
    pathReads: [],
  };
  const lineOf = lineIndex(source);
  const keyList = [...declared];
  const ctx: WalkContext = { ts, declared, keyList, lineOf, facts, needles };

  if (dialect === null) {
    const sf = trees.get(0) as TS.SourceFile;
    const first = sf.statements[0];
    if (first !== undefined && ts.isExpressionStatement(first) && ts.isStringLiteral(first.expression) && first.expression.text === 'use server') {
      facts.serverCode = true;
    }
    facts.scopes.push(scopeOf(ctx, [{ sf, base: 0 }], []));
  } else {
    // A component's scripts share one scope with its markup; a client script
    // (`own`) is a scope of its own.
    const regions = code.regions.map((r) => ({ region: r, tree: { sf: trees.get(r.start) as TS.SourceFile, base: r.start } }));
    const markup: Tree[] = [];
    const scanned: Span[] = [];
    const regionStarts = new Set(code.regions.map((r) => r.start));
    const inNonCode = spanTest(code.nonCode);
    for (const span of code.code) {
      if (regionStarts.has(span.start)) continue;
      const sf = source[span.start] === '{' ? trees.get(span.start + 1) : undefined;
      const clean = sf !== undefined && parseDiagnosticsOf(sf).length === 0;
      if (clean) markup.push({ sf, base: span.start + 1 });
      else scanned.push(span);
    }
    facts.scopes.push(
      scopeOf(
        ctx,
        [...regions.filter((r) => r.region.own !== true).map((r) => r.tree), ...markup],
        scanned.map((span) => ({ span, source, inNonCode })),
      ),
    );
    for (const r of regions) if (r.region.own === true) facts.scopes.push(scopeOf(ctx, [r.tree], []));
  }
  return facts;
}

interface Tree {
  sf: TS.SourceFile;
  /** Where the tree's text starts in the file. */
  base: number;
}

interface WalkContext {
  ts: typeof import('typescript');
  declared: ReadonlySet<string>;
  keyList: string[];
  lineOf: (offset: number) => number;
  facts: FileFacts;
  needles: PathNeedles;
}

/** Markup text the compiler could not take as one expression: read by tokens. */
interface Scanned {
  span: Span;
  source: string;
  inNonCode: (at: number) => boolean;
}

const unwrap = (ts: typeof import('typescript'), node: TS.Expression): TS.Expression => {
  let at = node;
  while (
    ts.isParenthesizedExpression(at) ||
    ts.isAsExpression(at) ||
    ts.isSatisfiesExpression(at) ||
    ts.isTypeAssertionExpression(at) ||
    ts.isNonNullExpression(at)
  ) {
    at = at.expression;
  }
  return at;
};

const isLiteral = (ts: typeof import('typescript'), node: TS.Node | undefined): node is TS.StringLiteral | TS.NoSubstitutionTemplateLiteral =>
  node !== undefined && (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node));

/**
 * One scope's imports and binding reads. Candidates are every name an import,
 * a `require` or an `import()` declares, every alias or destructure of a
 * candidate, and every call of one (a hook's result); whether
 * a candidate is a stet binding is decided across files, from the module its
 * root is imported from.
 */
function scopeOf(ctx: WalkContext, trees: Tree[], scanned: Scanned[]): Scope {
  const { ts, declared, facts, lineOf } = ctx;
  const scope: Scope = { imports: [], reads: [], exported: [], wrappers: [], exportedNames: [], aliased: [], loose: [] };
  // A name can trace to several roots (the same name declared in two
  // functions, or twice over); each is judged, and a root is added once so the
  // fixed point below ends.
  const roots = new Map<string, string[]>();
  const addRoot = (name: string, root: string): boolean => {
    const held = roots.get(name);
    if (held === undefined) roots.set(name, [root]);
    else if (held.includes(root)) return false;
    else held.push(root);
    return true;
  };

  const declare = (local: string, spec: string, imported: string): void => {
    scope.imports.push({ local, spec, imported });
    addRoot(local, local);
  };
  // The names a pattern binds off a module object; false where a shape is too loose to name them.
  const bindName = (name: TS.BindingName, spec: string): boolean => {
    if (ts.isIdentifier(name)) {
      declare(name.text, spec, '*');
      return true;
    }
    if (!ts.isObjectBindingPattern(name)) return false;
    let whole = true;
    for (const el of name.elements) {
      const member = el.propertyName === undefined ? undefined : ts.isComputedPropertyName(el.propertyName) ? null : el.propertyName.text;
      if (!ts.isIdentifier(el.name) || member === null) whole = false;
      else declare(el.name.text, spec, el.dotDotDotToken !== undefined ? '*' : (member ?? el.name.text));
    }
    return whole;
  };

  // A name that holds a namespace import: its members are roots of their own.
  const namespaceRoot = (root: string): boolean => scope.imports.some((i) => i.local === root && i.imported === '*');
  // A member of a namespace that is not a key: `R.useCopy` holds what the module exports under that name.
  const memberRoots = (expr: TS.Expression): string[] => {
    const at = unwrap(ts, expr);
    const name = ts.isPropertyAccessExpression(at) ? at.name.text : ts.isElementAccessExpression(at) && isLiteral(ts, at.argumentExpression) ? at.argumentExpression.text : undefined;
    const object = ts.isPropertyAccessExpression(at) || ts.isElementAccessExpression(at) ? unwrap(ts, at.expression) : undefined;
    if (name === undefined || declared.has(name) || object === undefined || !ts.isIdentifier(object)) return [];
    return (roots.get(object.text) ?? []).filter(namespaceRoot).map((root) => `${root}.${name}`);
  };

  // A candidate's use, widened through members that are not keys
  // (`DEFAULTS.default`, `copy.get`): the roots it traces to. A call of a
  // candidate is a root of its own: `useCopy()`.
  const rootsOf = (expr: TS.Expression): string[] => {
    const members = memberRoots(expr);
    let at = unwrap(ts, expr);
    for (;;) {
      if (ts.isPropertyAccessExpression(at) && !declared.has(at.name.text)) at = unwrap(ts, at.expression);
      else if (ts.isElementAccessExpression(at) && isLiteral(ts, at.argumentExpression) && !declared.has(at.argumentExpression.text)) {
        at = unwrap(ts, at.expression);
      } else break;
    }
    if (ts.isCallExpression(at)) {
      const callee = unwrap(ts, at.expression);
      const member = memberOf(ts, callee);
      const object = member === undefined ? callee : unwrap(ts, (callee as TS.PropertyAccessExpression).expression);
      const held = ts.isIdentifier(object) ? (roots.get(object.text) ?? []) : [];
      return held.filter((root) => parseCall(root) === null).map((root) => (member === undefined ? `${root}()` : `${root}.${member}()`));
    }
    return ts.isIdentifier(at) ? [...(roots.get(at.text) ?? []), ...members] : [];
  };

  // Declarations: imports, requires, and aliases to a fixed point.
  const declarations: Array<{ decl: TS.VariableDeclaration; tree: Tree }> = [];
  for (const tree of trees) {
    const { sf, base } = tree;
    const textOf = (node: TS.Node): string => node.getText(sf).replace(/\s+/g, ' ').slice(0, CAUSE_TEXT);
    const visit = (node: TS.Node): void => {
      if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier)) {
        const spec = node.moduleSpecifier.text;
        if (isStetPackage(spec)) facts.importsStet = true;
        const clause = node.importClause;
        if (clause === undefined || clause.isTypeOnly) return;
        if (clause.name !== undefined) declare(clause.name.text, spec, 'default');
        const named = clause.namedBindings;
        if (named !== undefined && ts.isNamespaceImport(named)) declare(named.name.text, spec, '*');
        if (named !== undefined && ts.isNamedImports(named)) {
          for (const el of named.elements) if (!el.isTypeOnly) declare(el.name.text, spec, (el.propertyName ?? el.name).text);
        }
        return;
      }
      if (ts.isImportEqualsDeclaration(node) && ts.isExternalModuleReference(node.moduleReference)) {
        const ref = node.moduleReference.expression;
        if (!node.isTypeOnly && ts.isStringLiteral(ref)) {
          if (isStetPackage(ref.text)) facts.importsStet = true;
          declare(node.name.text, ref.text, '*');
        }
        return;
      }
      if (ts.isExportDeclaration(node) && node.moduleSpecifier !== undefined && ts.isStringLiteral(node.moduleSpecifier)) {
        if (isStetPackage(node.moduleSpecifier.text)) facts.importsStet = true;
        if (!node.isTypeOnly) {
          facts.reexports.push(node.moduleSpecifier.text);
          if (node.exportClause !== undefined && ts.isNamedExports(node.exportClause)) noteRenames(facts, node.exportClause);
        }
        return;
      }
      if (ts.isCallExpression(node)) {
        const spec = moduleOf(ts, node);
        if (spec !== undefined) {
          if (isStetPackage(spec)) facts.importsStet = true;
          const hold = (): void => {
            scope.loose.push({ spec, line: lineOf(base + node.getStart(sf)), text: textOf(node) });
          };
          if (!bindModule(ts, node, (name) => bindName(name, spec), (local, imported) => declare(local, spec, imported))) hold();
        }
      }
      if (ts.isVariableDeclaration(node)) declarations.push({ decl: node, tree });
      ts.forEachChild(node, visit);
    };
    visit(sf);
  }

  // A pattern off a candidate: a member that is not a key holds the map, so it
  // carries the root on — a nested pattern as much as a name, a rest element
  // as much as either. A computed member could be any key: a read of its own.
  const patternRoots = (pattern: TS.ObjectBindingPattern, root: string, emit: Tree | undefined): boolean => {
    let grew = false;
    for (const el of pattern.elements) {
      let member: string | undefined;
      if (el.propertyName === undefined) member = ts.isIdentifier(el.name) ? el.name.text : undefined;
      else if (ts.isComputedPropertyName(el.propertyName)) {
        const inner = unwrap(ts, el.propertyName.expression);
        if (!isLiteral(ts, inner)) {
          if (emit !== undefined) {
            const { sf, base } = emit;
            scope.reads.push({
              root,
              line: lineOf(base + el.getStart(sf)),
              text: el.getText(sf).replace(/\s+/g, ' ').slice(0, CAUSE_TEXT),
              prefixes: [],
            });
          }
          continue;
        }
        member = inner.text;
      } else member = el.propertyName.text;
      if (el.dotDotDotToken === undefined && member !== undefined && declared.has(member)) continue;
      if (ts.isIdentifier(el.name)) {
        if (addRoot(el.name.text, root)) grew = true;
        if (el.dotDotDotToken === undefined && member !== undefined && namespaceRoot(root) && addRoot(el.name.text, `${root}.${member}`)) grew = true;
      } else if (ts.isObjectBindingPattern(el.name) && patternRoots(el.name, root, emit)) grew = true;
    }
    return grew;
  };
  for (let grew = true; grew; ) {
    grew = false;
    for (const { decl } of declarations) {
      if (decl.initializer === undefined) continue;
      for (const root of rootsOf(decl.initializer)) {
        if (ts.isIdentifier(decl.name)) {
          if (addRoot(decl.name.text, root)) grew = true;
        } else if (ts.isObjectBindingPattern(decl.name) && patternRoots(decl.name, root, undefined)) grew = true;
      }
    }
  }
  for (const { decl, tree } of declarations) {
    if (decl.initializer === undefined || !ts.isObjectBindingPattern(decl.name)) continue;
    for (const root of rootsOf(decl.initializer)) patternRoots(decl.name, root, tree);
  }

  // Exports of a candidate under this file's own name, and of any local name.
  const exportRoots = (held: readonly string[], name: string): void => {
    for (const root of held) {
      if (parseCall(root) !== null) continue;
      scope.exported.push(root);
      scope.aliased.push({ root, name });
    }
  };
  for (const { sf } of trees) {
    for (const stmt of sf.statements) {
      const modifiers = ts.canHaveModifiers(stmt) ? ts.getModifiers(stmt) : undefined;
      const exportedHere = modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword) === true;
      const defaultHere = modifiers?.some((m) => m.kind === ts.SyntaxKind.DefaultKeyword) === true;
      if (ts.isFunctionDeclaration(stmt) && stmt.name !== undefined && exportedHere) {
        scope.exportedNames.push(stmt.name.text);
        if (defaultHere) facts.renames.push({ from: stmt.name.text, as: 'default' });
      } else if (ts.isVariableStatement(stmt) && exportedHere) {
        for (const decl of stmt.declarationList.declarations) {
          if (ts.isIdentifier(decl.name)) scope.exportedNames.push(decl.name.text);
          if (ts.isIdentifier(decl.name)) exportRoots(roots.get(decl.name.text) ?? [], decl.name.text);
        }
      } else if (ts.isExportDeclaration(stmt) && stmt.moduleSpecifier === undefined && stmt.exportClause !== undefined && ts.isNamedExports(stmt.exportClause)) {
        noteRenames(facts, stmt.exportClause);
        for (const el of stmt.exportClause.elements) {
          scope.exportedNames.push((el.propertyName ?? el.name).text);
          exportRoots(roots.get((el.propertyName ?? el.name).text) ?? [], el.name.text);
        }
      } else if (ts.isExportAssignment(stmt)) {
        const expr = unwrap(ts, stmt.expression);
        if (ts.isIdentifier(expr)) {
          scope.exportedNames.push(expr.text);
          facts.renames.push({ from: expr.text, as: 'default' });
        }
        exportRoots(rootsOf(stmt.expression), 'default');
      }
    }
  }

  // Uses: every reference to a candidate, and the file's calls and values.
  for (const tree of trees) walkUses(ctx, tree, roots, scope);
  for (const text of scanned) scanUses(ctx, text, roots, scope);
  return scope;
}

/** `export { a as b }`: the names a module goes on under. */
function noteRenames(facts: FileFacts, clause: TS.NamedExports): void {
  for (const el of clause.elements) {
    if (el.propertyName !== undefined && el.propertyName.text !== el.name.text) facts.renames.push({ from: el.propertyName.text, as: el.name.text });
  }
}

/** The module a `require('x')` or `import('x')` call names. */
function moduleOf(ts: typeof import('typescript'), call: TS.CallExpression): string | undefined {
  const [arg] = call.arguments;
  if (call.arguments.length !== 1 || !isLiteral(ts, arg)) return undefined;
  if (call.expression.kind === ts.SyntaxKind.ImportKeyword) return arg.text;
  return ts.isIdentifier(call.expression) && call.expression.text === 'require' ? arg.text : undefined;
}

/**
 * A `require(spec)` or `import(spec)` as a binding declaration: bound to a
 * name, destructured, taken a member of, or handed to a `.then` callback.
 * False where the module object goes anywhere else.
 */
function bindModule(
  ts: typeof import('typescript'),
  call: TS.CallExpression,
  bindName: (name: TS.BindingName) => boolean,
  declare: (local: string, imported: string) => void,
): boolean {
  const wrapped = (node: TS.Node): boolean =>
    (ts.isAwaitExpression(node.parent) || ts.isParenthesizedExpression(node.parent) || ts.isAsExpression(node.parent) || ts.isNonNullExpression(node.parent)) &&
    node.parent.expression === node;
  let at: TS.Node = call;
  while (wrapped(at)) at = at.parent;
  const p = at.parent;
  // `import(spec).then(({ copy }) => …)`
  if (ts.isPropertyAccessExpression(p) && p.expression === at && p.name.text === 'then' && ts.isCallExpression(p.parent) && p.parent.expression === p) {
    const callback = p.parent.arguments[0];
    const param = callback !== undefined && (ts.isArrowFunction(callback) || ts.isFunctionExpression(callback)) ? callback.parameters[0] : undefined;
    return param !== undefined && bindName(param.name);
  }
  // `require(spec).copy`
  if (ts.isPropertyAccessExpression(p) && p.expression === at) {
    let holder: TS.Node = p;
    while (wrapped(holder)) holder = holder.parent;
    const d = holder.parent;
    if (!ts.isVariableDeclaration(d) || d.initializer !== holder || !ts.isIdentifier(d.name)) return false;
    declare(d.name.text, p.name.text);
    return true;
  }
  // `const m = require(spec)`, `const { copy } = await import(spec)`
  return ts.isVariableDeclaration(p) && p.initializer === at && bindName(p.name);
}

/** Whether an identifier is a reference, not a declaration, a member name or a type. */
function isReference(ts: typeof import('typescript'), id: TS.Identifier): boolean {
  const p = id.parent;
  if (ts.isPropertyAccessExpression(p) && p.name === id) return false;
  if (ts.isQualifiedName(p) || ts.isTypeReferenceNode(p) || ts.isTypeQueryNode(p)) return false;
  if (ts.isImportSpecifier(p) || ts.isImportClause(p) || ts.isNamespaceImport(p) || ts.isExportSpecifier(p)) return false;
  if (
    (ts.isVariableDeclaration(p) ||
      ts.isParameter(p) ||
      ts.isBindingElement(p) ||
      ts.isImportEqualsDeclaration(p) ||
      ts.isFunctionDeclaration(p) ||
      ts.isFunctionExpression(p) ||
      ts.isClassDeclaration(p) ||
      ts.isClassExpression(p) ||
      ts.isInterfaceDeclaration(p) ||
      ts.isTypeAliasDeclaration(p) ||
      ts.isEnumDeclaration(p) ||
      ts.isEnumMember(p) ||
      ts.isPropertyAssignment(p) ||
      ts.isPropertyDeclaration(p) ||
      ts.isPropertySignature(p) ||
      ts.isMethodDeclaration(p) ||
      ts.isMethodSignature(p) ||
      ts.isGetAccessorDeclaration(p) ||
      ts.isSetAccessorDeclaration(p) ||
      ts.isTypeParameterDeclaration(p)) &&
    p.name === id
  ) {
    return false;
  }
  if (ts.isBindingElement(p) && p.propertyName === id) return false;
  if (ts.isJsxAttribute(p) || ts.isLabeledStatement(p) || ts.isBreakOrContinueStatement(p)) return false;
  return true;
}

/**
 * One tree's walk: each reference to a candidate classified (T1, T2 or a read
 * through a key name), B1 and B2 settled where the file alone can, and every
 * call and value use recorded for B1's adapter rule.
 */
function walkUses(ctx: WalkContext, tree: Tree, roots: ReadonlyMap<string, string[]>, scope: Scope): void {
  const { ts, facts, needles, lineOf } = ctx;
  const { sf, base } = tree;
  const visit = (node: TS.Node): void => {
    if (ts.isCallExpression(node)) recordCall(ctx, node);
    if (
      (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node) || ts.isTemplateHead(node) || ts.isTemplateMiddle(node) || ts.isTemplateTail(node)) &&
      namesData(needles, node.text) &&
      !isSpecifier(ts, node)
    ) {
      facts.pathReads.push({ line: lineOf(base + node.getStart(sf)), text: node.getText(sf).replace(/\s+/g, ' ').slice(0, CAUSE_TEXT) });
    }
    if (ts.isImportSpecifier(node) || ts.isExportSpecifier(node)) {
      // `import { t as tr }`, `export { t as tr }`: the function goes on under
      // another name, whose calls the adapter rule cannot see.
      if (node.propertyName !== undefined && node.propertyName.text !== node.name.text) facts.values.add(node.propertyName.text);
    }
    // `const { t: tr } = B` goes on under another name too, and so does a
    // function exported as the module's default (imported under any name).
    if (ts.isBindingElement(node) && node.propertyName !== undefined && !ts.isComputedPropertyName(node.propertyName)) {
      facts.values.add(node.propertyName.text);
    }
    if (ts.isFunctionDeclaration(node) && node.name !== undefined && node.modifiers?.some((m) => m.kind === ts.SyntaxKind.DefaultKeyword)) {
      facts.values.add(node.name.text);
    }
    if (ts.isIdentifier(node)) {
      if (isValueUse(ts, node)) facts.values.add(node.text);
      if (ts.isPropertyAccessExpression(node.parent) && node.parent.name === node && !isCallee(ts, node.parent)) facts.values.add(node.text);
      if (isReference(ts, node)) for (const root of roots.get(node.text) ?? []) scope.reads.push(...classify(ctx, scope, tree, node, root));
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
}

/**
 * Whether a string points at the snapshot or a generated data module: a path
 * that ends in a file name of theirs (`content/defaults.json`, `/defaults.json?v=1`),
 * or a glob over their folder. A sentence that mentions the file is no path.
 */
function namesData(needles: PathNeedles, text: string): boolean {
  const ends = (name: string): boolean => {
    for (let at = text.indexOf(name); at >= 0; at = text.indexOf(name, at + 1)) {
      const before = text[at - 1];
      const after = text[at + name.length];
      if ((before === undefined || before === '/' || before === '\\') && (after === undefined || after === '?' || after === '#')) return true;
    }
    return false;
  };
  return needles.names.some(ends) || (needles.folder !== null && text.includes(`${needles.folder}/`) && text.includes('*'));
}

/** Whether a string is a module specifier: `import … from 'x'`, `export … from 'x'`, `require('x')`, `import('x')`, `import x = require('x')`, `typeof import('x')`. */
function isSpecifier(ts: typeof import('typescript'), node: TS.Node): boolean {
  const p = node.parent;
  if (ts.isImportDeclaration(p) || ts.isExportDeclaration(p) || ts.isExternalModuleReference(p) || ts.isLiteralTypeNode(p)) return true;
  return ts.isCallExpression(p) && moduleOf(ts, p) === (node as TS.StringLiteral).text;
}

const isCallee = (ts: typeof import('typescript'), node: TS.Node): boolean => ts.isCallExpression(node.parent) && node.parent.expression === node;

/** A name used as a value: a reference that is not a callee. */
function isValueUse(ts: typeof import('typescript'), id: TS.Identifier): boolean {
  return isReference(ts, id) && !isCallee(ts, id);
}

/** A call by name (`t(…)`, `x.t(…)`): which argument positions carry a key-name literal, intersected over the file. */
function recordCall(ctx: WalkContext, call: TS.CallExpression): void {
  const { ts, declared, facts } = ctx;
  const callee = call.expression;
  const name = ts.isIdentifier(callee) ? callee.text : ts.isPropertyAccessExpression(callee) ? callee.name.text : undefined;
  if (name === undefined) return;
  const here: number[] = [];
  call.arguments.forEach((arg, i) => {
    if (isLiteral(ts, arg) && declared.has(arg.text)) here.push(i);
  });
  const held = facts.calls.get(name);
  if (held === undefined) facts.calls.set(name, { count: 1, keyAt: here });
  else facts.calls.set(name, { count: held.count + 1, keyAt: held.keyAt.filter((i) => here.includes(i)) });
}

/**
 * Widened through members that are not keys, as `rootOf` reads it: the
 * expression a candidate's reference is the root of.
 */
function widen(ctx: WalkContext, from: TS.Expression): TS.Expression {
  const { ts, declared } = ctx;
  let use = from;
  for (;;) {
    const p = use.parent;
    if (ts.isPropertyAccessExpression(p) && p.expression === use && !declared.has(p.name.text)) use = p;
    else if (ts.isElementAccessExpression(p) && p.expression === use && isLiteral(ts, p.argumentExpression) && !declared.has(p.argumentExpression.text)) use = p;
    else if ((ts.isNonNullExpression(p) || ts.isParenthesizedExpression(p)) && p.expression === use) use = p;
    else break;
  }
  return use;
}

/**
 * One reference to a candidate: the reads it makes, none where it reads a key
 * by name, is an alias's initializer or an export (tracked as declarations),
 * or hands a hook's result to an exported wrapper. A call of the candidate
 * with no argument is also a hook call where the callee is one, and its result
 * is a candidate of its own, judged under the root `<root>()`.
 */
function classify(ctx: WalkContext, scope: Scope, tree: Tree, id: TS.Identifier, root: string): Read[] {
  const { ts } = ctx;
  const use = widen(ctx, id);
  const out = classifyUse(ctx, scope, tree, use, root);
  const p = use.parent;
  if (ts.isCallExpression(p) && p.expression === use && parseCall(root) === null) {
    // `useCopy()` or `R.useCopy()`; a longer path is no hook call.
    let member: string | undefined | null = null;
    if (use === id) member = undefined;
    else if (unwrap(ts, (use as TS.PropertyAccessExpression).expression) === id) member = memberOf(ts, use);
    if (member !== null) {
      const call = out[0];
      if (call !== undefined) call.hook = member === undefined ? {} : { member };
      out.push(...classifyUse(ctx, scope, tree, widen(ctx, p), member === undefined ? `${root}()` : `${root}.${member}()`));
    }
  }
  return out;
}

/** The member a property access or a literal element access names; undefined for any other expression. */
function memberOf(ts: typeof import('typescript'), use: TS.Expression): string | undefined {
  if (ts.isPropertyAccessExpression(use)) return use.name.text;
  return ts.isElementAccessExpression(use) && isLiteral(ts, use.argumentExpression) ? use.argumentExpression.text : undefined;
}

/** `node` and the parentheses, assertions and non-null marks round it. */
function climb(ts: typeof import('typescript'), node: TS.Expression): TS.Expression {
  let at = node;
  while (
    (ts.isParenthesizedExpression(at.parent) ||
      ts.isAsExpression(at.parent) ||
      ts.isSatisfiesExpression(at.parent) ||
      ts.isTypeAssertionExpression(at.parent) ||
      ts.isNonNullExpression(at.parent)) &&
    at.parent.expression === at
  ) {
    at = at.parent;
  }
  return at;
}

/** Whether a call's callee is imported from `@getstet/stet` or a subpath of it, or is `Object.keys`, which lists names and reads no value. */
function exemptCallee(ctx: WalkContext, scope: Scope, call: TS.CallExpression | TS.NewExpression): boolean {
  const { ts } = ctx;
  const callee = unwrap(ts, call.expression);
  const stetImport = (local: string): boolean => scope.imports.some((i) => i.local === local && isStetPackage(i.spec));
  if (ts.isIdentifier(callee)) return stetImport(callee.text);
  if (!ts.isPropertyAccessExpression(callee)) return false;
  const object = unwrap(ts, callee.expression);
  if (!ts.isIdentifier(object)) return false;
  return (object.text === 'Object' && callee.name.text === 'keys') || stetImport(object.text);
}

/** The reads one candidate expression (already widened) makes. */
function classifyUse(ctx: WalkContext, scope: Scope, tree: Tree, use: TS.Expression, root: string): Read[] {
  const { ts, lineOf } = ctx;
  const { sf, base } = tree;
  const p = use.parent;
  const read = (node: TS.Node, prefixes: string[], t1?: TS.Expression): Read => {
    const out: Read = {
      root,
      line: lineOf(base + node.getStart(sf)),
      text: node.getText(sf).replace(/\s+/g, ' ').slice(0, CAUSE_TEXT),
      prefixes,
    };
    const placed = t1 === undefined ? null : placement(ctx, t1);
    if (placed === 'keys') out.placed = true;
    else if (placed !== null) out.adapter = placed;
    return out;
  };

  // A key read by name: `copy.hero_title`, `copy['hero_title']`, `copy('hero_title')`. A key
  // named like a member of the API (`default`, `bind`, `get`) is one only where nothing is called
  // or indexed off the access: `DEFAULTS.default[k]` and `copy.bind(null)` read the object.
  if (ts.isPropertyAccessExpression(p) && p.expression === use) {
    const top = climb(ts, p);
    const q = top.parent;
    const reads = (ts.isCallExpression(q) && q.expression === top) || (ts.isElementAccessExpression(q) && q.expression === top && !isLiteral(ts, q.argumentExpression));
    return reads ? classifyUse(ctx, scope, tree, p, root) : [];
  }
  if (ts.isElementAccessExpression(p) && p.expression === use) {
    return isLiteral(ts, p.argumentExpression) ? [] : [read(p, prefixOfArgument(ctx, p.argumentExpression), p.argumentExpression)];
  }
  if (ts.isCallExpression(p) && p.expression === use) {
    const first = p.arguments[0];
    if (isLiteral(ts, first)) return [];
    return [read(p, first === undefined ? [] : prefixOfArgument(ctx, first), first)];
  }
  if (ts.isTaggedTemplateExpression(p) && p.tag === use) return [read(p, prefixOfArgument(ctx, p.template))];
  // Declarations and exports, tracked apart.
  if (ts.isVariableDeclaration(p) && p.initializer === use) return [];
  if (ts.isExportAssignment(p)) return [];
  // A hook's result returned by an exported function: that function is a hook
  // in turn, and its callers hold the result.
  if (parseCall(root) !== null) {
    const name = wrapperOf(ctx, scope, use);
    if (name !== undefined) {
      scope.wrappers.push({ name, root });
      return [];
    }
  }
  // T2: the map as a value. An argument of another call learns from that
  // call's other arguments (`slice(DEFAULTS.default, HERO)`).
  const asValue = (out: Read): Read => {
    const member = memberOf(ts, use);
    out.value = member === undefined ? {} : { member };
    return out;
  };
  const top = climb(ts, use);
  const call = top.parent;
  if (ts.isCallExpression(call) || ts.isNewExpression(call)) {
    const args: readonly TS.Expression[] = call.arguments ?? [];
    if (args.includes(top)) {
      const out = read(call, prefixesOfSiblings(ctx, args, top));
      if (exemptCallee(ctx, scope, call)) out.exemptArg = true;
      return [asValue(out)];
    }
  }
  if (ts.isJsxExpression(p) && ts.isJsxAttribute(p.parent)) {
    const out = asValue(read(p.parent, []));
    // The JSX twin of exemptCallee: a prop handed to an element bound to a stet import (the provider's `resolved`).
    const tag = p.parent.parent.parent.tagName;
    if (ts.isIdentifier(tag) && scope.imports.some((i) => i.local === tag.text && isStetPackage(i.spec))) out.exemptArg = true;
    return [out];
  }
  return [asValue(read(p, []))];
}

/**
 * The exported function whose return value `use` is — `return use`, an arrow's
 * body, or `use` held in an object or array that is returned — by the name it
 * is exported under. Undefined where `use` goes elsewhere, or the function is
 * not exported or has no name.
 */
function wrapperOf(ctx: WalkContext, scope: Scope, use: TS.Expression): string | undefined {
  const { ts } = ctx;
  let node: TS.Node = use;
  for (;;) {
    const p = node.parent;
    if (
      ts.isParenthesizedExpression(p) ||
      ts.isAsExpression(p) ||
      ts.isSatisfiesExpression(p) ||
      ts.isNonNullExpression(p) ||
      ts.isTypeAssertionExpression(p) ||
      ts.isArrayLiteralExpression(p) ||
      ts.isObjectLiteralExpression(p) ||
      ts.isShorthandPropertyAssignment(p) ||
      (ts.isPropertyAssignment(p) && p.initializer === node)
    ) {
      node = p;
    } else break;
  }
  const p = node.parent;
  let fn: TS.Node | undefined;
  if (ts.isReturnStatement(p)) {
    for (let up: TS.Node | undefined = p.parent; up !== undefined && fn === undefined; up = up.parent) if (ts.isFunctionLike(up)) fn = up;
  } else if (ts.isArrowFunction(p) && p.body === node) fn = p;
  if (fn === undefined) return undefined;
  let name: string | undefined;
  if (ts.isFunctionDeclaration(fn)) name = fn.name?.text ?? (fn.modifiers?.some((m) => m.kind === ts.SyntaxKind.DefaultKeyword) ? 'default' : undefined);
  else if (ts.isArrowFunction(fn) || ts.isFunctionExpression(fn)) {
    const holder = fn.parent;
    if (ts.isVariableDeclaration(holder) && holder.initializer === fn && ts.isIdentifier(holder.name)) name = holder.name.text;
    else if (ts.isExportAssignment(holder) && holder.expression === fn) name = 'default';
  }
  return name === 'default' || (name !== undefined && scope.exportedNames.includes(name)) ? name : undefined;
}

/** Whether an expression is a string literal, or a ternary whose two arms each are (`a ? 'x' : b ? 'y' : 'z'`). */
function literalArms(ts: typeof import('typescript'), node: TS.Expression): boolean {
  const at = unwrap(ts, node);
  return isLiteral(ts, at) || (ts.isConditionalExpression(at) && literalArms(ts, at.whenTrue) && literalArms(ts, at.whenFalse));
}

/**
 * B1: whether a T1 read's key argument is followed to key names in this file —
 * a `const` holding one, the parameter of a callback over an array of them, a
 * loop variable over one, a lookup map of them, none of them mutated or let out
 * of the file's sight (`escaped`) — or is a
 * parameter of a function declared here, placed when every call of that
 * function passes a key-name literal at its position (settled across files).
 */
function placement(ctx: WalkContext, arg: TS.Expression): 'keys' | { name: string; index: number } | null {
  const { ts } = ctx;
  const at = unwrap(ts, arg);
  // `copy(a ? 'x' : 'y')`: both arms name keys, and a ternary may stand in either arm.
  if (ts.isConditionalExpression(at)) return literalArms(ts, at) ? 'keys' : null;
  const isKey = (node: TS.Expression | undefined): boolean => {
    const u = node === undefined ? undefined : unwrap(ts, node);
    return isLiteral(ts, u) && ctx.declared.has(u.text);
  };
  const constInit = (id: TS.Identifier): TS.Expression | undefined => {
    const local = resolveLocal(ts, id);
    return local?.kind === 'const' && local.init !== undefined ? unwrap(ts, local.init) : undefined;
  };
  const keyArray = (node: TS.Expression): boolean => {
    const init = ts.isIdentifier(node) ? constInit(node) : undefined;
    return (
      init !== undefined &&
      ts.isArrayLiteralExpression(init) &&
      init.elements.length > 0 &&
      init.elements.every((el) => isKey(el)) &&
      !mutated(ts, node as TS.Identifier) &&
      !escaped(ts, node as TS.Identifier)
    );
  };

  if (ts.isIdentifier(at)) {
    const local = resolveLocal(ts, at);
    if (local === null) return null;
    if (local.kind === 'const') return isKey(local.init) ? 'keys' : null;
    if (local.kind === 'forof') return keyArray(local.stmt.expression) ? 'keys' : null;
    if (local.kind !== 'param') return null;
    const fn = local.fn;
    const holder = fn.parent;
    // `KEYS.map((k) => copy(k))`
    if (
      local.index === 0 &&
      (ts.isArrowFunction(fn) || ts.isFunctionExpression(fn)) &&
      ts.isCallExpression(holder) &&
      holder.arguments[0] === fn &&
      ts.isPropertyAccessExpression(holder.expression) &&
      ['map', 'forEach', 'filter'].includes(holder.expression.name.text) &&
      keyArray(holder.expression.expression)
    ) {
      return 'keys';
    }
    // `function t(k) { … }`, `const t = (k) => …`
    if (ts.isFunctionDeclaration(fn) && fn.name !== undefined) return { name: fn.name.text, index: local.index };
    if (
      (ts.isArrowFunction(fn) || ts.isFunctionExpression(fn)) &&
      ts.isVariableDeclaration(holder) &&
      holder.initializer === fn &&
      ts.isIdentifier(holder.name) &&
      ts.isVariableDeclarationList(holder.parent) &&
      (holder.parent.flags & ts.NodeFlags.Const) !== 0
    ) {
      return { name: holder.name.text, index: local.index };
    }
    return null;
  }
  // `copy(LABEL[s])`, `copy(LABEL.open)` over a map of key names.
  const map = ts.isElementAccessExpression(at) || ts.isPropertyAccessExpression(at) ? unwrap(ts, at.expression) : undefined;
  if (map !== undefined && ts.isIdentifier(map)) {
    const init = constInit(map);
    if (
      init !== undefined &&
      ts.isObjectLiteralExpression(init) &&
      init.properties.length > 0 &&
      init.properties.every((prop) => ts.isPropertyAssignment(prop) && isKey(prop.initializer)) &&
      !mutated(ts, map) &&
      !escaped(ts, map)
    ) {
      return 'keys';
    }
  }
  return null;
}

/** Per file, the names code lets out of reach of a plain read: exported, aliased, handed to a call, returned. */
const escapes = new WeakMap<TS.SourceFile, Set<string>>();

/**
 * Whether a name leaves the file's sight: it is exported, or some reference to
 * it is anything but a plain read — the receiver of a member (`KEYS.map`), the
 * subject of an index (`LABEL[s]`), a `for…of` or `for…in` expression or a spread. An
 * array or a map that escapes can be changed where no scan looks. Any name
 * that spells it counts, so a shadowing local is judged to escape too.
 */
function escaped(ts: typeof import('typescript'), id: TS.Identifier): boolean {
  const sf = id.getSourceFile();
  let held = escapes.get(sf);
  if (held === undefined) {
    const names = new Set<string>();
    held = names;
    escapes.set(sf, names);
    const visit = (node: TS.Node): void => {
      if (ts.isIdentifier(node) && isReference(ts, node)) {
        const top = climb(ts, node);
        const q = top.parent;
        const plain =
          ((ts.isPropertyAccessExpression(q) || ts.isElementAccessExpression(q)) && q.expression === top) ||
          ((ts.isForOfStatement(q) || ts.isForInStatement(q)) && q.expression === top) ||
          ts.isSpreadElement(q);
        if (!plain) names.add(node.text);
      }
      if (ts.isExportSpecifier(node)) names.add((node.propertyName ?? node.name).text);
      if (ts.isVariableStatement(node) && node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword) === true) {
        for (const decl of node.declarationList.declarations) if (ts.isIdentifier(decl.name)) names.add(decl.name.text);
      }
      ts.forEachChild(node, visit);
    };
    visit(sf);
  }
  return held.has(id.text);
}

/** Per file, the names code adds to or assigns into after their declaration. */
const mutations = new WeakMap<TS.SourceFile, Set<string>>();

/**
 * Whether the file changes the array or map a `const` name holds: a call of
 * `push`, `unshift`, `splice`, `fill` or `copyWithin` on it, `Object.assign` to
 * it, or an assignment into one of its elements or properties. Any name that
 * spells it counts, so a shadowing local is judged mutated too.
 */
function mutated(ts: typeof import('typescript'), id: TS.Identifier): boolean {
  const sf = id.getSourceFile();
  let held = mutations.get(sf);
  if (held === undefined) {
    const names = new Set<string>();
    held = names;
    mutations.set(sf, names);
    const rootName = (node: TS.Expression): string | undefined => {
      let at = unwrap(ts, node);
      while (ts.isPropertyAccessExpression(at) || ts.isElementAccessExpression(at)) at = unwrap(ts, at.expression);
      return ts.isIdentifier(at) ? at.text : undefined;
    };
    const visit = (node: TS.Node): void => {
      if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression)) {
        const receiver = rootName(node.expression.expression);
        if (receiver !== undefined && MUTATORS.has(node.expression.name.text)) names.add(receiver);
        const target = node.arguments[0];
        if (
          target !== undefined &&
          node.expression.name.text === 'assign' &&
          ts.isIdentifier(node.expression.expression) &&
          node.expression.expression.text === 'Object'
        ) {
          const assigned = rootName(target);
          if (assigned !== undefined) names.add(assigned);
        }
      }
      if (
        ts.isBinaryExpression(node) &&
        node.operatorToken.kind >= ts.SyntaxKind.FirstAssignment &&
        node.operatorToken.kind <= ts.SyntaxKind.LastAssignment &&
        (ts.isElementAccessExpression(unwrap(ts, node.left)) || ts.isPropertyAccessExpression(unwrap(ts, node.left)))
      ) {
        const assigned = rootName(node.left);
        if (assigned !== undefined) names.add(assigned);
      }
      ts.forEachChild(node, visit);
    };
    visit(sf);
  }
  return held.has(id.text);
}

/**
 * B2 for a T1 read: the prefix its argument opens with. A key-shaped prefix is
 * learnt from the head of a template literal, the leftmost operand of a `+`
 * chain, or a `const` that is that operand — a literal anywhere else (inside
 * an index, a branch, a `??` operand, a call, an array) says nothing of which
 * keys the read reaches.
 */
function prefixOfArgument(ctx: WalkContext, arg: TS.Node): string[] {
  const head = opening(ctx, arg as TS.Expression, true);
  return head === undefined ? [] : prefixes(ctx, [head]);
}

/**
 * B2 for a T2 read: the prefixes the call it is an argument of carries in its
 * other arguments — a literal, a template head, a `const` of either, or an
 * array of them (`slice(DEFAULTS.default, ['home_live_'])`).
 */
function prefixesOfSiblings(ctx: WalkContext, args: readonly TS.Expression[], use: TS.Expression): string[] {
  const { ts } = ctx;
  const heads: string[] = [];
  const list = (node: TS.Expression, hop: boolean): void => {
    const at = unwrap(ts, node);
    if (ts.isArrayLiteralExpression(at)) {
      for (const el of at.elements) {
        const head = opening(ctx, el, false);
        if (head !== undefined) heads.push(head);
      }
      return;
    }
    if (hop && ts.isIdentifier(at) && isReference(ts, at)) {
      const local = resolveLocal(ts, at);
      if (local?.kind === 'const' && local.init !== undefined) {
        list(local.init, false);
        return;
      }
    }
    const head = opening(ctx, at, false);
    if (head !== undefined) heads.push(head);
  };
  for (const arg of args) if (arg !== use) list(arg, true);
  return prefixes(ctx, heads);
}

/** The literal text an expression opens with: a string, a template's head, the leftmost operand of a `+` chain, a `const` of either. */
function opening(ctx: WalkContext, node: TS.Expression, hop: boolean): string | undefined {
  const { ts } = ctx;
  const at = unwrap(ts, node);
  if (isLiteral(ts, at)) return at.text;
  if (ts.isTemplateExpression(at)) return at.head.text;
  if (ts.isBinaryExpression(at) && at.operatorToken.kind === ts.SyntaxKind.PlusToken) return opening(ctx, at.left, hop);
  if (hop && ts.isIdentifier(at) && isReference(ts, at)) {
    const local = resolveLocal(ts, at);
    if (local?.kind === 'const' && local.init !== undefined) return opening(ctx, local.init, false);
  }
  return undefined;
}

/** The heads that are a proper prefix of at least one declared key and end at `_`. */
function prefixes(ctx: WalkContext, heads: readonly string[]): string[] {
  const { declared, keyList } = ctx;
  return [...new Set(heads)].filter((text) => text.endsWith('_') && !declared.has(text) && keyList.some((key) => key.startsWith(text)));
}

type Local =
  | { kind: 'const'; init: TS.Expression | undefined }
  | { kind: 'param'; fn: TS.SignatureDeclaration; index: number }
  | { kind: 'forof'; stmt: TS.ForOfStatement }
  | { kind: 'other' };

/** Whether a binding pattern declares `name`. */
function patternDeclares(ts: typeof import('typescript'), pattern: TS.BindingName, name: string): boolean {
  if (ts.isIdentifier(pattern)) return pattern.text === name;
  return pattern.elements.some((el) => !ts.isOmittedExpression(el) && patternDeclares(ts, el.name, name));
}

/** The declaration an identifier refers to, by the nearest enclosing scope that declares its name; null where none in the file does. */
function resolveLocal(ts: typeof import('typescript'), id: TS.Identifier): Local | null {
  const name = id.text;
  for (let node: TS.Node = id; node.parent !== undefined; node = node.parent) {
    const scope = node.parent;
    if (ts.isFunctionLike(scope)) {
      const params = scope.parameters;
      for (let i = 0; i < params.length; i++) {
        const param = params[i] as TS.ParameterDeclaration;
        if (ts.isIdentifier(param.name) && param.name.text === name) return { kind: 'param', fn: scope, index: i };
        if (!ts.isIdentifier(param.name) && patternDeclares(ts, param.name, name)) return { kind: 'other' };
      }
    }
    if ((ts.isForOfStatement(scope) || ts.isForInStatement(scope) || ts.isForStatement(scope)) && scope.initializer !== undefined && ts.isVariableDeclarationList(scope.initializer)) {
      for (const decl of scope.initializer.declarations) {
        if (!patternDeclares(ts, decl.name, name)) continue;
        return ts.isForOfStatement(scope) && ts.isIdentifier(decl.name) ? { kind: 'forof', stmt: scope } : { kind: 'other' };
      }
    }
    if (ts.isCatchClause(scope) && scope.variableDeclaration !== undefined && patternDeclares(ts, scope.variableDeclaration.name, name)) {
      return { kind: 'other' };
    }
    if (ts.isBlock(scope) || ts.isSourceFile(scope) || ts.isModuleBlock(scope) || ts.isCaseClause(scope) || ts.isDefaultClause(scope)) {
      for (const stmt of scope.statements) {
        if (ts.isVariableStatement(stmt)) {
          for (const decl of stmt.declarationList.declarations) {
            if (!patternDeclares(ts, decl.name, name)) continue;
            const isConst = (stmt.declarationList.flags & ts.NodeFlags.Const) !== 0;
            return isConst && ts.isIdentifier(decl.name) ? { kind: 'const', init: decl.initializer } : { kind: 'other' };
          }
        } else if ((ts.isFunctionDeclaration(stmt) || ts.isClassDeclaration(stmt) || ts.isEnumDeclaration(stmt)) && stmt.name?.text === name) {
          return { kind: 'other' };
        } else if (ts.isImportDeclaration(stmt) && stmt.importClause !== undefined) {
          const clause = stmt.importClause;
          const named = clause.namedBindings;
          if (
            clause.name?.text === name ||
            (named !== undefined && ts.isNamespaceImport(named) && named.name.text === name) ||
            (named !== undefined && ts.isNamedImports(named) && named.elements.some((el) => el.name.text === name))
          ) {
            return { kind: 'other' };
          }
        }
      }
    }
  }
  return null;
}

/**
 * Markup the compiler could not read as one expression — a tag's interior, a
 * Vue directive's value, a Svelte block — read by tokens: each candidate there
 * that is not followed by a key read by name is a cause, with no prefix, its
 * text the markup it sits in.
 */
function scanUses(ctx: WalkContext, scanned: Scanned, roots: ReadonlyMap<string, string[]>, scope: Scope): void {
  const { declared, lineOf } = ctx;
  const { span, source, inNonCode } = scanned;
  const text = source.slice(span.start, span.end);
  for (const [name, held] of roots) {
    const pattern = new RegExp(`(?<![\\w$])(?:(?<!\\.)|(?<=\\.\\.\\.))${name.replace(/\$/g, '\\$')}(?![\\w$])`, 'g');
    for (const m of text.matchAll(pattern)) {
      const at = span.start + m.index;
      if (inNonCode(at)) continue;
      const after = source.slice(at + name.length, span.end);
      const member = /^\s*\??\.\s*([A-Za-z_$][\w$]*)/.exec(after);
      if (member !== null && declared.has(member[1] as string)) continue;
      if (/^\s*(?:\.\s*get\s*)?\(\s*(['"])[^'"\n]*\1\s*[,)]/.test(after)) continue;
      if (/^\s*\[\s*(['"])[^'"\n]*\1\s*\]/.test(after)) continue;
      for (const root of held) scope.reads.push({ root, line: lineOf(at), text: text.replace(/\s+/g, ' ').slice(0, CAUSE_TEXT), prefixes: [] });
    }
  }
}
